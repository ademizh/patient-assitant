"""The appointment record: one coherent object for the before, during and after stages.

Every piece of content carries its ORIGIN so patient statements, doctor instructions,
AI explanations, the patient's own documents and knowledge-base sources stay distinguishable:

    patient           - typed or dictated by the patient (intake entries, questions, notes)
    patient_document  - text from a document the patient uploaded/pasted (e.g. test results)
    doctor            - the doctor's instructions as supplied by the patient (verbatim)
    ai                - generated by the AI model (or by demo heuristics in demo mode)
    knowledge_base    - excerpts from the indexed medical documents (with real metadata)
    rules             - output of deterministic rules (e.g. DEMO urgent-care rules)

Persistence: one folder per record under APPOINTMENTS_PATH:
    <id>/record.json      the record (UTF-8 JSON)
    <id>/uploads/...      files the patient uploaded for this record
Records are stored separately from the medical knowledge collection (Chroma) and are never
indexed into it. `RecordStore.delete` removes the folder including all uploads.
"""

