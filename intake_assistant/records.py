_ID_RE = re.compile(r"^[a-f0-9]{12}$")


class RecordSummary(BaseModel):
    id: str
    title: str
    created_at: str
    updated_at: str
    appointment_date: str | None
    fictional: bool
    n_entries: int
    n_actions: int


def _safe_name(name: str) -> str:
    base = Path(name).name
    base = re.sub(r"[^\w.\-]", "_", base, flags=re.UNICODE)[:100]
    return base or "file"


class RecordStore:
    """One folder per appointment record. Kept apart from the medical-document store."""

    def __init__(self, root: Path):
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)

    def _dir(self, record_id: str) -> Path:
        if not _ID_RE.match(record_id or ""):
            raise ValueError("Недопустимый идентификатор записи.")
        return self.root / record_id

    def exists(self, record_id: str) -> bool:
        try:
            return (self._dir(record_id) / "record.json").exists()
        except ValueError:
            return False

    def save(self, record: AppointmentRecord) -> None:
        d = self._dir(record.id)
        d.mkdir(parents=True, exist_ok=True)
        record.updated_at = utcnow_iso()
        tmp = d / "record.json.tmp"
        tmp.write_text(record.model_dump_json(indent=2), encoding="utf-8")
        os.replace(tmp, d / "record.json")

    def load(self, record_id: str) -> AppointmentRecord:
        path = self._dir(record_id) / "record.json"
        return AppointmentRecord.model_validate_json(path.read_text(encoding="utf-8"))

    def list_records(self) -> list[RecordSummary]:
        out = []
        for p in self.root.glob("*/record.json"):
            try:
                data = json.loads(p.read_text(encoding="utf-8"))
                out.append(
                    RecordSummary(
                        id=data["id"], title=data.get("title", ""), created_at=data.get("created_at", ""),
                        updated_at=data.get("updated_at", ""),
                        appointment_date=data.get("appointment_date"), fictional=bool(data.get("fictional")),
                        n_entries=len(data.get("intake", {}).get("entries", [])),
                        n_actions=len(data.get("actions", [])),
                    )
                )
            except (OSError, ValueError, KeyError):
                continue
        # Stable order (newest created first); saving a record never re-orders the list.
        return sorted(out, key=lambda r: (r.created_at, r.id), reverse=True)

    def most_recent(self) -> RecordSummary | None:
        recs = self.list_records()
        return max(recs, key=lambda r: r.updated_at) if recs else None

    def delete(self, record_id: str) -> bool:
        """Delete the record AND all of its uploads. Returns True if something was removed."""
        d = self._dir(record_id)
        if not d.exists():
            return False
        shutil.rmtree(d)
        return True

    # ---- uploads ----------------------------------------------------------------------

    def save_upload(self, record: AppointmentRecord, filename: str, data: bytes, kind: str) -> UploadedFile:
        up_dir = self._dir(record.id) / "uploads"
        up_dir.mkdir(parents=True, exist_ok=True)
        uid = next_id("U", record.uploads)
        stored = f"{uid}__{_safe_name(filename)}"
        (up_dir / stored).write_bytes(data)
        meta = UploadedFile(
            id=uid, filename=Path(filename).name, stored_name=stored, kind=kind,  # type: ignore[arg-type]
            sha256=hashlib.sha256(data).hexdigest(), size=len(data),
        )
        record.uploads.append(meta)
        return meta

    def upload_path(self, record: AppointmentRecord, upload: UploadedFile) -> Path:
        return self._dir(record.id) / "uploads" / upload.stored_name

    def delete_upload(self, record: AppointmentRecord, upload_id: str) -> None:
        up = record.find_upload(upload_id)
        if up is None:
            return
        self.upload_path(record, up).unlink(missing_ok=True)
        record.uploads = [u for u in record.uploads if u.id != upload_id]
