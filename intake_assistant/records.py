class ActionItem(BaseModel):
    id: str  # A1 ...
    category: ActionCategory
    description: str
    source_statement: str  # verbatim wording of the doctor's instruction ("" for patient-added items)
    instruction_id: str | None = None
    added_by: Literal["doctor_instruction", "patient"] = "doctor_instruction"
    doctor_due_text: str | None = None  # verbatim deadline wording, if the doctor gave one
    doctor_due_date: str | None = None  # ISO date, only if the wording was an explicit calendar date
    due_date_note: str | None = None
    patient_target_date: str | None = None  # ISO date chosen by the patient (shown differently)
    medication: MedicationDetails | None = None
    status: Literal["pending", "done"] = "pending"
    completed_at: str | None = None
    flags: list[str] = Field(default_factory=list)
    patient_note: str = ""
    edited_by_patient: bool = False
    # Medication items only: what the medicine is, from the knowledge base (checklist graph, Week 10).
    explanation: Explanation | None = None
    created_at: str = Field(default_factory=utcnow_iso)

    @property
    def origin(self) -> str:
        return "doctor" if self.added_by == "doctor_instruction" else "patient"

    def effective_date(self) -> tuple[date | None, str | None]:
        """(date, 'doctor'|'patient') - the doctor's explicit date wins over the patient's target."""
        for value, who in ((self.doctor_due_date, "doctor"), (self.patient_target_date, "patient")):
            if value:
                try:
                    return date.fromisoformat(value), who
                except ValueError:
                    continue
        return None, None


