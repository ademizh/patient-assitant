class AppointmentRecord(BaseModel):
    schema_version: str = RECORD_SCHEMA_VERSION
    id: str = Field(default_factory=lambda: uuid.uuid4().hex[:12])
    title: str = "Новая запись о приёме"
    appointment_date: str | None = None  # ISO, entered by the patient
    created_at: str = Field(default_factory=utcnow_iso)
    updated_at: str = Field(default_factory=utcnow_iso)
    fictional: bool = False

    # Before the appointment
    intake: IntakeSession = Field(default_factory=IntakeSession)
    patient_questions: list[PatientQuestion] = Field(default_factory=list)
    specialist_guidance: SpecialistGuidance | None = None
    urgent_check: UrgentCheck | None = None
    report: DoctorReport | None = None
    report_signature: str | None = None

    # During the appointment
    consultation_items: list[ConsultationItem] = Field(default_factory=list)
    explanations: list[Explanation] = Field(default_factory=list)  # saved by the patient

    # After the appointment
    instructions: list[DoctorInstruction] = Field(default_factory=list)
    actions: list[ActionItem] = Field(default_factory=list)
    instruction_issues: list[InstructionIssue] = Field(default_factory=list)
    actions_signature: str | None = None
    actions_generator: str | None = None

    uploads: list[UploadedFile] = Field(default_factory=list)

    # ---- helpers ----------------------------------------------------------------------

    def is_empty(self) -> bool:
        return not (
            self.intake.entries or self.patient_questions or self.consultation_items or self.explanations
            or self.instructions or self.actions or self.uploads
        )

    def intake_signature(self) -> str:
        s = self.intake
        raw = "|".join(f"{e.id}:{e.text}" for e in s.entries) + f"#{sorted(s.skipped_slots)}#{s.finished}"
        return hashlib.sha256(raw.encode()).hexdigest()

    def instructions_signature(self) -> str:
        raw = "|".join(f"{d.id}:{d.text}" for d in self.instructions)
        return hashlib.sha256(raw.encode()).hexdigest()

    def report_is_stale(self) -> bool:
        return self.report is not None and self.report_signature != self.intake_signature()

    def actions_are_stale(self) -> bool:
        return bool(self.instructions) and self.actions_signature != self.instructions_signature()

    def find_upload(self, upload_id: str | None) -> UploadedFile | None:
        return next((u for u in self.uploads if u.id == upload_id), None)


def next_id(prefix: str, existing: list) -> str:
    """Next sequential ID ('Q3'); never reuses an ID even after deletions."""
    nums = []
    for item in existing:
        m = re.match(rf"^{prefix}(\d+)$", getattr(item, "id", "") or "")
        if m:
            nums.append(int(m.group(1)))
    return f"{prefix}{max(nums, default=0) + 1}"


# ---- Patient questions ---------------------------------------------------------------


def sync_questions_from_intake(record: AppointmentRecord) -> int:
    """Copy questions the patient stated during intake into the question list (no duplicates).

    Returns the number of questions added. Questions are patient wording; nothing is rephrased.
    """
    ex = record.intake.extraction
    if ex is None:
        return 0
    known = {re.sub(r"\s+", " ", q.text.strip().lower()) for q in record.patient_questions}
    entries = record.intake.entry_map()
    added = 0
    for f in ex.facts:
        if f.category != "patient_question" or f.negated:
            continue
        ids = [i for i in f.source_entry_ids if i in entries]
        if not ids:
            continue
        key = re.sub(r"\s+", " ", f.statement.strip().lower())
        if key in known:
            continue
        record.patient_questions.append(
            PatientQuestion(id=next_id("Q", record.patient_questions), text=f.statement.strip(),
                            source="intake", entry_ids=ids)
        )
        known.add(key)
        added += 1
    return added


